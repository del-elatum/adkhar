/* =========================================================
   HELPERS
========================================================= */

function getCurrentDhikr() {
  return adhkar[currentTime][currentPage];
}


function formatTime(seconds) {
  if (!Number.isFinite(seconds)) {
    return '0:00';
  }

  const minutes = Math.floor(seconds / 60);

  const remainingSeconds = Math.floor(seconds % 60)
    .toString()
    .padStart(2, '0');

  return `${minutes}:${remainingSeconds}`;
}


/* =========================================================
   UPDATE PAGE
========================================================= */

function updateContent() {
  const currentList = adhkar[currentTime];
  const item = getCurrentDhikr();

  dhikrText.textContent = item[currentLanguage];

  pageCounter.textContent =
    `${currentPage + 1} / ${currentList.length}`;

  if (currentLanguage === 'arabic') {
    dhikrText.classList.add('arabic-text');
    dhikrText.classList.remove('secondary-text');
  } else {
    dhikrText.classList.remove('arabic-text');
    dhikrText.classList.add('secondary-text');
  }

  updateRepeatInfo();
  updateNavigationButtons();
}


function updateRepeatInfo() {
  const item = getCurrentDhikr();

  if (item.repeat > 1) {
    if (autoplayEnabled) {
      repeatInfo.textContent =
        `Repeat ${item.repeat} times · ${currentRepeat} / ${item.repeat}`;
    } else {
      repeatInfo.textContent =
        `Repeat ${item.repeat} times`;
    }

    repeatInfo.classList.add('visible');
  } else {
    repeatInfo.textContent = '';
    repeatInfo.classList.remove('visible');
  }
}


function updateNavigationButtons() {
  const currentList = adhkar[currentTime];

  previousButton.disabled = currentPage === 0;

  nextButton.disabled =
    currentPage === currentList.length - 1;
}


/* =========================================================
   AUDIO
========================================================= */

function resetAudioUI() {
  progressFill.style.width = '0%';
  currentAudioTime.textContent = '0:00';
  audioDuration.textContent = '0:00';
  playIcon.textContent = '▶';
}


function loadCurrentAudio() {
  const item = getCurrentDhikr();

  audio.pause();

  audio.src = item.audio;
  audio.load();

  resetAudioUI();
}


function stopAudio() {
  audio.pause();

  try {
    audio.currentTime = 0;
  } catch (error) {
    // Audio may not have loaded yet.
  }

  resetAudioUI();
}


function playCurrentAudio() {
  const playPromise = audio.play();

  if (playPromise !== undefined) {
    playPromise
      .then(() => {
        playIcon.textContent = '❚❚';
      })
      .catch((error) => {
        console.error('Audio could not play:', error);

        if (autoplayEnabled) {
          stopAutoplay();
        }
      });
  }
}


/* =========================================================
   PLAY / PAUSE
========================================================= */

playButton.addEventListener('click', () => {

  if (audio.paused) {
    playCurrentAudio();
  } else {
    audio.pause();
    playIcon.textContent = '▶';
  }

});


audio.addEventListener('play', () => {
  playIcon.textContent = '❚❚';
});


audio.addEventListener('pause', () => {
  if (!audio.ended) {
    playIcon.textContent = '▶';
  }
});


/* =========================================================
   AUDIO TIME + PROGRESS
========================================================= */

audio.addEventListener('loadedmetadata', () => {

  audioDuration.textContent =
    formatTime(audio.duration);

});


audio.addEventListener('timeupdate', () => {

  currentAudioTime.textContent =
    formatTime(audio.currentTime);

  if (!audio.duration) {
    progressFill.style.width = '0%';
    return;
  }

  const percentage =
    (audio.currentTime / audio.duration) * 100;

  progressFill.style.width =
    `${percentage}%`;

});


progressBar.addEventListener('click', (event) => {

  if (!audio.duration) {
    return;
  }

  const rect =
    progressBar.getBoundingClientRect();

  const position =
    (event.clientX - rect.left) / rect.width;

  audio.currentTime =
    Math.max(
      0,
      Math.min(position, 1)
    ) * audio.duration;

});


/* =========================================================
   AUTOPLAY
========================================================= */

function startAutoplay() {

  autoplayEnabled = true;
  currentRepeat = 1;

  autoplayButton.classList.add('active');

  autoplayButton.innerHTML = `
    <span class="autoplay-icon">■</span>
    <span>Stop Auto</span>
  `;

  updateRepeatInfo();

  stopAudio();

  audio.src = getCurrentDhikr().audio;
  audio.load();

  playCurrentAudio();
}


function stopAutoplay() {

  autoplayEnabled = false;
  currentRepeat = 1;

  autoplayButton.classList.remove('active');

  autoplayButton.innerHTML = `
    <span class="autoplay-icon">▶</span>
    <span>Autoplay</span>
  `;

  stopAudio();
  updateRepeatInfo();
}


autoplayButton.addEventListener('click', () => {

  if (autoplayEnabled) {
    stopAutoplay();
  } else {
    startAutoplay();
  }

});


/* =========================================================
   WHEN AUDIO FINISHES
========================================================= */

audio.addEventListener('ended', () => {

  playIcon.textContent = '▶';

  /*
    NORMAL MANUAL PLAY
  */

  if (!autoplayEnabled) {
    audio.currentTime = 0;
    progressFill.style.width = '0%';
    currentAudioTime.textContent = '0:00';
    return;
  }


  /*
    AUTOPLAY:
    REPEAT CURRENT PAGE IF NEEDED
  */

  const item = getCurrentDhikr();

  if (currentRepeat < item.repeat) {

    currentRepeat++;

    updateRepeatInfo();

    audio.currentTime = 0;

    playCurrentAudio();

    return;
  }


  /*
    CURRENT DHIKR IS COMPLETE.
    MOVE TO NEXT PAGE.
  */

  const currentList =
    adhkar[currentTime];

  if (currentPage < currentList.length - 1) {

    currentPage++;
    currentRepeat = 1;

    updateContent();

    audio.src = getCurrentDhikr().audio;
    audio.load();

    playCurrentAudio();

  } else {

    /*
      FINAL PAGE COMPLETE
    */

    autoplayEnabled = false;
    currentRepeat = 1;

    autoplayButton.classList.remove('active');

    autoplayButton.innerHTML = `
      <span class="autoplay-icon">▶</span>
      <span>Autoplay</span>
    `;

    resetAudioUI();
    updateRepeatInfo();
  }

});


/* =========================================================
   MORNING / NIGHT
========================================================= */

timeButtons.forEach((button) => {

  button.addEventListener('click', () => {

    const selectedTime =
      button.dataset.time;

    if (selectedTime === currentTime) {
      return;
    }


    /*
      Switching Morning/Night always
      stops autoplay and audio.
    */

    if (autoplayEnabled) {
      stopAutoplay();
    } else {
      stopAudio();
    }


    currentTime = selectedTime;
    currentPage = 0;
    currentRepeat = 1;


    timeButtons.forEach((btn) => {
      btn.classList.remove('active');
    });

    button.classList.add('active');


    updateContent();
    loadCurrentAudio();

  });

});


/* =========================================================
   LANGUAGE
========================================================= */

languageButtons.forEach((button) => {

  button.addEventListener('click', () => {

    currentLanguage =
      button.dataset.language;


    languageButtons.forEach((btn) => {
      btn.classList.remove('active');
    });

    button.classList.add('active');


    /*
      IMPORTANT:
      We ONLY update text here.

      Audio and autoplay continue
      uninterrupted.
    */

    updateContent();

  });

});


/* =========================================================
   PREVIOUS PAGE
========================================================= */

previousButton.addEventListener('click', () => {

  if (currentPage === 0) {
    return;
  }


  /*
    Manual page navigation stops autoplay.
  */

  if (autoplayEnabled) {
    stopAutoplay();
  } else {
    stopAudio();
  }


  currentPage--;
  currentRepeat = 1;

  updateContent();
  loadCurrentAudio();

});


/* =========================================================
   NEXT PAGE
========================================================= */

nextButton.addEventListener('click', () => {

  const currentList =
    adhkar[currentTime];

  if (
    currentPage >=
    currentList.length - 1
  ) {
    return;
  }


  /*
    Manual page navigation stops autoplay.
  */

  if (autoplayEnabled) {
    stopAutoplay();
  } else {
    stopAudio();
  }


  currentPage++;
  currentRepeat = 1;

  updateContent();
  loadCurrentAudio();

});


/* =========================================================
   INITIAL LOAD
========================================================= */

updateContent();
loadCurrentAudio();
